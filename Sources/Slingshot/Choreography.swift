// Heavily basde on HasChor, a Haskell library for choreographic programming,
// where choreographies are ordinary monadic code and projection happens by interpreting the same code once per participant.
// Sets of locations and values located at several of them come from MultiChor, HasChor's successor.

import Foundation

/// A set of nodes. Declare one with `@Locations` and the `Includes` of each member:
///
///     @Locations
///     enum Peers: Initiator.Includes, Responder.Includes {}
///
/// The conformances are the set's definition, so membership is checked by the compiler.
public protocol LocationSet: Sendable {
    /// Who's in the set, for projection to send to each of them
    static var members: [any Location.Type] { get }

    /// The effects `parallel` bodies can use at every location of the set. Declare it in the `@Locations` enum:
    /// `typealias Shared = PeerShared`, where each member's `Local` has all of PeerShared's families.
    /// By default, `NoEffects`: the bodies are pure.
    associatedtype Shared: EffectStack

    /// A program in the set's shared effects, as one of its members' local program.
    /// Generated by `@Location` and `@Locations`, which only compile when every member's `Local` has the shared families.
    static func lift<L: Location, V: ~Copyable>(_ program: consuming Freer<Shared, V>, at member: Member<L, Self>) -> Freer<L.Local, V>
}

public extension LocationSet {
    static func contains(_ location: any Location.Type) -> Bool {
        members.contains { ObjectIdentifier($0) == ObjectIdentifier(location) }
    }
}

/// A node in a distributed system, identified by a string. Declare one with `@Location`.
/// A location is also the set of just itself, so a value at one location is an `At<Server, V>`.
/// As a set of one, its shared effects are all of its local ones.
public protocol Location: LocationSet where Shared == Local {
    static var name: String { get }

    /// Reads the values this location holds, inside `locally`: generated by `@Location`
    associatedtype Reader: LocationReader

    /// The effects this location's local code can use, in `locally`. By default, just `Embedding`.
    associatedtype Local: EffectStack = Embedding.Family
}

public extension Location {
    static var members: [any Location.Type] { [Self.self] }
}

/// Only compiles when `Stack` is an effect stack: `@Location` and `@Locations` name it with `Local` and `Shared`,
/// so declaring one that isn't a stack fails right there instead of where the location is first used.
/// A family is the stack `SomeFamily.Family`, not the `@EffectFamily` enum itself.
public enum EffectStackCheck<Stack: EffectStack> {}

/// What `@Location` generates as `Reader`: only `locally`, running at the location, makes one.
public protocol LocationReader {
    /// Only for `locally` and `@Location`'s generated code: a reader made elsewhere could read values that aren't there
    init(_unchecked: Void)
}

/// A value held by every location in `S`. At any other location it's empty.
/// Copyable exactly when its value is: a noncopyable one, like a session, is used once with `locally(consuming:)`,
/// or read with `locally(borrowing:)`.
public struct At<S: LocationSet, Value: ~Copyable>: ~Copyable {
    fileprivate var value: Value?

    /// Within Slingshot only: outside it, a value only becomes located through a choreography
    init(value: consuming Value?) {
        self.value = value
    }

    /// Whether this node holds the value
    var isHeld: Bool {
        switch value {
        case .some: true
        case .none: false
        }
    }

    public static var absent: Self { .init(value: nil) }

    /// Only for projection and `@Location`'s generated readers: inside a choreography, read with a location's reader
    public consuming func take() -> Value {
        switch consume value {
        case .some(let value):
            return value
        case .none:
            preconditionFailure("\(Value.self) isn't held at this location")
        }
    }
}
extension At: Copyable where Value: Copyable {}
extension At: Sendable where Value: Sendable & ~Copyable {}

extension At where Value: ~Copyable {
    /// The value transformed where it's held, and still absent elsewhere
    consuming func map<Mapped: ~Copyable>(_ transform: (consuming Value) -> Mapped) -> At<S, Mapped> {
        switch consume value {
        case .some(let value):
            return At<S, Mapped>(value: transform(value))
        case .none:
            return .absent
        }
    }

    /// A transformation of the value where it's held, leaving the value itself in place
    borrowing func borrowMap<Mapped: ~Copyable>(_ transform: (borrowing Value) -> Mapped) -> At<S, Mapped> {
        switch value {
        case .some(let value):
            return At<S, Mapped>(value: transform(value))
        case .none:
            return .absent
        }
    }
}

/// A proof that `L` is in `S`, for code that's generic over its locations.
/// Get one from `L.member(of: S.self)`, which only compiles when `S` conforms to `L.Includes`.
public struct Member<L: Location, S: LocationSet>: Sendable {
    /// Only for `@Location`'s `member(of:)`: making one by hand claims a membership the compiler hasn't checked
    public init(_unchecked: Void) {}

    /// Reads a value held by `S`, at `L`
    public func read<V: ~Copyable>(_ v: consuming At<S, V>, with reader: L.Reader) -> V {
        v.take()
    }
}

/// A proof that every location in `Sub` is in `Outer`, for `conclave`.
/// Get one from `Sub.subset(of: Outer.self)`, which only compiles when `Outer` conforms to each member's `Includes`.
public struct Subset<Sub: LocationSet, Outer: LocationSet>: Sendable {
    /// Only for the generated `subset(of:)`: making one by hand claims an inclusion the compiler hasn't checked
    public init(_unchecked: Void) {}
}

public extension Subset where Sub == Outer {
    /// Every set is a subset of itself
    static var whole: Self { .init(_unchecked: ()) }
}

/// Reads the values every member of `S` holds, inside `congruently`.
public struct Congruent<S: LocationSet> {
    fileprivate init() {}

    public func callAsFunction<V>(_ v: At<S, V>) -> V {
        v.take()
    }
}

/// A value each location in `S` holds its own version of, like each peer's nonce: same type, possibly different values.
/// Made by `parallel`; a location in `S` reads its own facet with its reader, and `fanIn` gathers them all.
/// Copyable exactly when its value is: a noncopyable one, like each peer's session, is used with
/// `parallel(consuming:)` or read with `parallel(borrowing:)`.
public struct Faceted<S: LocationSet, Value: ~Copyable>: ~Copyable {
    fileprivate var value: Value?
    /// The location holding `value`, by name: a `parallel` body over the facets runs there
    fileprivate var holder: String?

    /// Within Slingshot only: outside it, a facet only comes from `parallel` or `faceted(…)`
    init(value: consuming Value?, at location: (any Location.Type)?) {
        self.value = value
        self.holder = location?.name
    }

    /// Whether this node holds a facet
    var isHeld: Bool {
        switch value {
        case .some: true
        case .none: false
        }
    }

    public static var absent: Self { .init(value: nil, at: nil) }

    /// Only for projection and `@Location`'s generated readers: inside a choreography, read with a location's reader
    public consuming func take() -> Value {
        switch consume value {
        case .some(let value):
            return value
        case .none:
            preconditionFailure("this node holds no facet of \(S.self)")
        }
    }

    /// The location holding the facet: only asked where it's held, which is always one of `S`'s members
    private var holderLocation: any Location.Type {
        guard let holder, let location = S.members.first(where: { $0.name == holder }) else {
            preconditionFailure("a facet of \(S.self) held outside its members")
        }
        return location
    }

    /// The facet transformed where it's held, with the location holding it
    consuming func map<Mapped: ~Copyable>(_ transform: (any Location.Type, consuming Value) -> Mapped) -> Faceted<S, Mapped> {
        let location: (any Location.Type)? = isHeld ? holderLocation : nil
        switch consume value {
        case .some(let value):
            return Faceted<S, Mapped>(value: transform(location!, value), at: location)
        case .none:
            return .absent
        }
    }

    /// A transformation of the facet where it's held, leaving the facet itself in place
    borrowing func borrowMap<Mapped: ~Copyable>(_ transform: (any Location.Type, borrowing Value) -> Mapped) -> Faceted<S, Mapped> {
        switch value {
        case .some(let value):
            let location = holderLocation
            return Faceted<S, Mapped>(value: transform(location, value), at: location)
        case .none:
            return .absent
        }
    }
}
extension Faceted: Copyable where Value: Copyable {}
extension Faceted: Sendable where Value: Sendable & ~Copyable {}

extension Faceted where Value: ~Copyable {
    /// Only for `@Locations`' `faceted(…)`, which adds one value per member of `S`, starting from `absent`: a member's
    /// value becomes this node's facet where it's held. Used any other way, it claims facets the compiler hasn't checked.
    public consuming func _unchecked<L: Location>(adding piece: consuming At<L, Value>) -> Faceted<S, Value> {
        switch piece.release() {
        case .some(let value):
            // the members are all different, so a node holds at most one of their values
            return Faceted(value: value, at: L.self)
        case .none:
            return self
        }
    }
}

extension At where Value: ~Copyable {
    /// The value where it's held, nil elsewhere
    fileprivate consuming func release() -> Value? {
        switch consume value {
        case .some(let value):
            return value
        case .none:
            return nil
        }
    }
}

/// Reads what the location running a `parallel` body holds: values held by all of `S`, and its own facets.
public struct Facet<S: LocationSet> {
    /// The location this body is running at
    public let location: any Location.Type

    fileprivate init(location: any Location.Type) {
        self.location = location
    }

    public func callAsFunction<V: ~Copyable>(_ v: consuming At<S, V>) -> V {
        v.take()
    }

    public func callAsFunction<V: ~Copyable>(_ facets: consuming Faceted<S, V>) -> V {
        facets.take()
    }
}

/// Every location of `S`'s facet, gathered by `fanIn`: one value per member.
public struct Quire<S: LocationSet, Value> {
    fileprivate var values: [String: Value]

    /// The facet of one member: the proof makes asking for a non-member a compile error
    public subscript<L: Location>(_ member: Member<L, S>) -> Value {
        values[L.name]!
    }

    /// Every facet, in the order of `S.members`
    public var all: [Value] {
        S.members.map { values[$0.name]! }
    }
}
extension Quire: Sendable where Value: Sendable {}

