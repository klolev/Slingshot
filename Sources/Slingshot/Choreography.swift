@EffectFamily
public enum Choreography {
    public protocol Interpreter {
        /// runs a local computation at one location L
        func locally<L: Location, ComputationOutput: ~Copyable>(
            _ type: L.Type,
            _ body: @escaping (L.Reader) -> Freer<L.Local, ComputationOutput>
        ) async throws -> At<L, ComputationOutput>

        /// runs a local program at L that was already built from a value L holds: what `locally(consuming:)` and
        /// `locally(borrowing:)` make, so their bodies can take the value as a parameter instead of capturing it
        func locallyRun<L: Location, ComputationOutput: ~Copyable>(
            _ program: consuming At<L, Freer<L.Local, ComputationOutput>>
        ) async throws -> At<L, ComputationOutput>

        /// sends a value at location Sender to every location in Receivers: they all hold it afterwards
        func send<Sender: Location, Receivers: LocationSet, Value: Codable & Sendable>(
            _ v: At<Sender, Value>,
            to: Receivers.Type
        ) async throws -> At<Receivers, Value>

        /// computes the same value at every location in S, from values they all hold: no communication
        func congruently<S: LocationSet, CongruentOutput>(
            _ locations: S.Type,
            _ body: @escaping (Congruent<S>) -> CongruentOutput
        ) async throws -> At<S, CongruentOutput>

        /// runs the same local code at every location in S, each producing its own facet: no communication.
        /// The code can use S's shared effects, which run with each location's own local interpreter.
        func parallel<S: LocationSet, FacetOutput: ~Copyable>(
            _ locations: S.Type,
            _ body: @escaping (Facet<S>) -> Freer<S.Shared, FacetOutput>
        ) async throws -> Faceted<S, FacetOutput>

        /// runs at every location in S a program already built from its facet: what `parallel(consuming:)` and
        /// `parallel(borrowing:)` make, so their bodies can take the facet as a parameter instead of capturing it
        func parallelRun<S: LocationSet, FacetOutput: ~Copyable>(
            _ programs: consuming Faceted<S, Freer<S.Shared, FacetOutput>>
        ) async throws -> Faceted<S, FacetOutput>

        /// sends every location in S's facet to every location in Receivers, who then hold all of them
        func fanIn<S: LocationSet, Receivers: LocationSet, Value: Codable & Sendable>(
            _ facets: Faceted<S, Value>,
            to: Receivers.Type
        ) async throws -> At<Receivers, Quire<S, Value>>

        /// a value held by the whole census as a plain value: every participant holds it, so they all take the
        /// same path through the code after it. Use `Choreography.naked(_:)`, which supplies the census.
        func naked<S: LocationSet, V>(_ v: At<S, V>, in census: Census<S>) async throws -> V

        /// a sub-choreography among Sub only: everyone else skips it and holds nothing of its result.
        /// Use `Choreography.conclave(_:_:_:)`, which supplies the census.
        func conclave<Outer: LocationSet, Sub: LocationSet, B>(
            _ participants: Sub.Type,
            in census: Census<Outer>,
            _ subset: Subset<Sub, Outer>,
            _ body: @escaping () -> Freer<Within<Sub>, B>
        ) async throws -> At<Sub, B>

        /// branches depending on value V at location L
        func branch<L: Location, Value: Codable & Sendable, BranchOutput>(
            _ v: At<L, Value>,
            _ body: @escaping (Value) -> Freer<Choreography.Family, BranchOutput>
        ) async throws -> BranchOutput
    }
}

@EffectFamily
public enum Networking {
    public protocol Interpreter {
        func send<V: Codable & Sendable>(_ value: V, to location: String) async throws
        func receive<V: Codable & Sendable>(_ type: V.Type, from location: String) async throws -> V
        func broadcast<V: Codable & Sendable>(_ value: V) async throws
    }
}

/// Plain async code as an effect: a location's local steps, and `congruently` bodies. What it produces can be
/// noncopyable, like a session made with `try` inside `parallel`.
@EffectFamily
public enum Embedding {
    public protocol Interpreter {
        func run<V: ~Copyable>(_ body: @escaping () async throws -> V) async throws -> V
    }
}

/// Translates a choreography into the program one location runs: its local code, plus the messages it sends and receives.
public struct Projector<Me: Location>: Choreography.Translation {
    public typealias Target = Choreography.Node<Me.Local>

    public init() {}

    public func locally<L, ComputationOutput: ~Copyable>(
        _ type: L.Type,
        _ body: @escaping (L.Reader) -> Freer<L.Local, ComputationOutput>
    ) -> Freer<Target, At<L, ComputationOutput>> where L : Location {
        guard Me.self == L.self else {
            return .pure(.absent)
        }

        // L is Me, so L.Local is Me.Local, Swift just can't learn type equality from the comparison above
        let program = unsafeReinterpret(body(L.Reader(_unchecked: ())), as: Freer<Me.Local, ComputationOutput>.self)
        return program.translate(LiftIntoNode<Me.Local>())
            .map { At(value: $0) }
    }

    public func locallyRun<L, ComputationOutput: ~Copyable>(
        _ program: consuming At<L, Freer<L.Local, ComputationOutput>>
    ) -> Freer<Target, At<L, ComputationOutput>> where L : Location {
        guard Me.self == L.self else {
            return .pure(.absent)
        }

        // held here, since this is L: the program was built where the value it came from is held
        let local = unsafeReinterpret(program.take(), as: Freer<Me.Local, ComputationOutput>.self)
        return local.translate(LiftIntoNode<Me.Local>())
            .map { At(value: $0) }
    }

    public func send<Sender, Receivers, Value>(
        _ v: At<Sender, Value>,
        to: Receivers.Type
    ) -> Freer<Target, At<Receivers, Value>> where Sender : Location, Receivers : LocationSet, Value : Codable & Sendable {
        let received = Receivers.contains(Me.self)

        if Sender.self == Me.self {
            let value = v.take()
            // the sender keeps its own copy instead of sending it to itself
            let others = Receivers.members.filter { ObjectIdentifier($0) != ObjectIdentifier(Me.self) }
            var sent = Freer<Target, Void>.pure(())
            for receiver in others {
                sent = sent.flatMap { _ in Networking.send(value, to: receiver.name) }
            }
            let result: At<Receivers, Value> = received ? .init(value: value) : .absent
            return sent.map { _ in result }
        }

        if received {
            return Networking.receive(Value.self, from: Sender.name)
                .map { At(value: $0) }
        }

        return .pure(.absent)
    }

    public func congruently<S, CongruentOutput>(
        _ locations: S.Type,
        _ body: @escaping (Congruent<S>) -> CongruentOutput
    ) -> Freer<Target, At<S, CongruentOutput>> where S : LocationSet {
        guard S.contains(Me.self) else {
            return .pure(.absent)
        }

        // run when the program gets here, not when it's translated: "pure" is only a convention for the body
        return Embedding.run {
            .init(value: body(Congruent()))
        }
    }

    public func parallel<S, FacetOutput: ~Copyable>(
        _ locations: S.Type,
        _ body: @escaping (Facet<S>) -> Freer<S.Shared, FacetOutput>
    ) -> Freer<Target, Faceted<S, FacetOutput>> where S : LocationSet {
        guard S.contains(Me.self) else {
            return .pure(.absent)
        }

        // Me is in S: the comparison above is the proof
        let program = S.lift(body(Facet(location: Me.self)), at: Member<Me, S>(_unchecked: ()))
        return program.translate(LiftIntoNode<Me.Local>())
            .map { Faceted(value: $0, at: Me.self) }
    }

    public func parallelRun<S, FacetOutput: ~Copyable>(
        _ programs: consuming Faceted<S, Freer<S.Shared, FacetOutput>>
    ) -> Freer<Target, Faceted<S, FacetOutput>> where S : LocationSet {
        guard S.contains(Me.self) else {
            return .pure(.absent)
        }

        // held here, since Me is in S: the program was built from Me's facet
        let program = S.lift(programs.take(), at: Member<Me, S>(_unchecked: ()))
        return program.translate(LiftIntoNode<Me.Local>())
            .map { Faceted(value: $0, at: Me.self) }
    }

    public func fanIn<S, Receivers, Value>(
        _ facets: Faceted<S, Value>,
        to: Receivers.Type
    ) -> Freer<Target, At<Receivers, Quire<S, Value>>> where S : LocationSet, Receivers : LocationSet, Value : Codable & Sendable {
        let isMe = { (location: any Location.Type) in ObjectIdentifier(location) == ObjectIdentifier(Me.self) }

        // a member sends its facet to every receiver but itself
        var program: Freer<Target, Void> = .pure(())
        if S.contains(Me.self) {
            let mine = facets.take()
            for receiver in Receivers.members where !isMe(receiver) {
                program = program.flatMap { _ in Networking.send(mine, to: receiver.name) }
            }
        }

        guard Receivers.contains(Me.self) else {
            return program.map { _ in .absent }
        }

        // a receiver collects every member's facet, its own included without a message
        var gathered = program.map { _ in [String: Value]() }
        for member in S.members {
            gathered = gathered.flatMap { values in
                if isMe(member) {
                    return .pure(values.merging([member.name: facets.take()]) { $1 })
                }
                return Networking.receive(Value.self, from: member.name)
                    .map { values.merging([member.name: $0]) { $1 } }
            }
        }
        return gathered.map { .init(value: Quire(values: $0)) }
    }

    public func naked<S, V>(_ v: At<S, V>, in census: Choreography.Census<S>) -> Freer<Target, V> where S : LocationSet {
        // only participants are projected, and every participant holds a value located at the census
        .pure(v.take())
    }

    public func conclave<Outer, Sub, B>(
        _ participants: Sub.Type,
        in census: Choreography.Census<Outer>,
        _ subset: Subset<Sub, Outer>,
        _ body: @escaping () -> Freer<Choreography.Within<Sub>, B>
    ) -> Freer<Target, At<Sub, B>> where Outer : LocationSet, Sub : LocationSet {
        guard Sub.contains(Me.self) else {
            return .pure(.absent)
        }

        return Choreography.translate(body(), with: self)
            .map { At(value: $0) }
    }

    public func branch<L, Value, BranchOutput>(
        _ v: At<L, Value>,
        _ body: @escaping (Value) -> Freer<Choreography.Family, BranchOutput>
    ) -> Freer<Target, BranchOutput> where L : Location, Value: Codable & Sendable {
        let broadcast: Freer<Target, Value> = if Me.self == L.self {
            Networking.broadcast(v.take())
                .map { _ in v.take() }
        } else {
            Networking.receive(Value.self, from: L.name)
        }

        return broadcast.flatMap {
            Choreography.translate(body($0), with: self)
        }
    }
}

public extension Choreography {
    /// That a program's participants are exactly `S`. Only Slingshot makes one, so census-dependent operations
    /// can only be reached through `Choreography.naked` and `Choreography.conclave`, where the census is the program's own.
    struct Census<S: LocationSet>: Sendable {
        init() {}
    }

    /// The stack of a choreography whose participants are exactly `S`: its census.
    /// Knowing the census lets a value held by all of it be used as a plain value (`naked`), and lets a sub-choreography
    /// run among fewer participants (`conclave`), which is how MultiChor branches without telling uninvolved locations.
    ///
    ///     let program: Freer<Choreography.Within<Everyone>, Done> = #do { bind in … }
    ///     let atServer = Choreography.project(program, as: Server.member(of: Everyone.self))
    enum Within<S: LocationSet>: Has {
        public typealias Interpreter = Choreography.Family.Interpreter

        public static func inject<X: ~Copyable>(_ effect: consuming any Effect<Choreography.Family, X> & ~Copyable) -> any Effect<Within<S>, X> & ~Copyable {
            Rehomed<S, X>.rehomed(effect)
        }
    }

    /// A choreography effect in a `Within<S>` program: the same effect, run by the same interpreter.
    enum Rehomed<S: LocationSet, X: ~Copyable>: Effect, ~Copyable {
        public typealias Family = Within<S>
        public typealias Output = X

        case rehomed(any Effect<Choreography.Family, X> & ~Copyable)

        /// The choreography effect itself
        consuming func take() -> any Effect<Choreography.Family, X> & ~Copyable {
            switch consume self {
            case .rehomed(let effect):
                return effect
            }
        }

        public consuming func accept(_ interpreter: any Choreography.Interpreter) async throws -> X {
            switch consume self {
            case .rehomed(let effect):
                return try await runEffect(effect, as: X.self, with: interpreter)
            }
        }
    }

    /// A constant at one location: it's written in the choreography, so making it takes no communication.
    /// Not an overload of `locally`: a trailing closure could be taken for the constant.
    static func constant<Effs: Has, L: Location, V>(_ value: V, at location: L.Type) -> Freer<Effs, At<L, V>> {
        locally(location) { _ in .pure(value) }
    }

    /// Runs local code at the location holding `owned`, which takes the value: for a noncopyable one, like a session,
    /// that a later step uses up. The location comes from the value.
    ///
    /// The body runs when the choreography reaches this step, only where the value is held, and builds the local
    /// program from it; that program then runs as the step. Write `consume session` inside `#do`, so the block carries
    /// the session to this step.
    ///
    ///     let keys = bind(Choreography.locally(consuming: consume session) { reader, session in
    ///         .pure(session.finish(with: reader(peerTag)))
    ///     })
    static func locally<Effs: Has, L: Location, Owned: ~Copyable, ComputationOutput: ~Copyable>(
        consuming owned: consuming At<L, Owned>,
        _ body: (L.Reader, consuming Owned) -> Freer<L.Local, ComputationOutput>
    ) -> Freer<Effs, At<L, ComputationOutput>> {
        // held only at L, so the reader is only made there
        locallyRun(owned.map { body(L.Reader(_unchecked: ()), $0) })
    }

    /// Runs local code at the location holding `borrowed`, which reads the value and leaves it in place:
    /// for reading a noncopyable value, like a session's public key, before a later step consumes it.
    /// The body runs when the choreography reaches this step, like `locally(consuming:)`'s, so what it reads is
    /// read then: copy it into the program it returns.
    ///
    ///     let y = bind(Choreography.locally(borrowing: session) { _, session in .pure(session.Y) })
    static func locally<Effs: Has, L: Location, Borrowed: ~Copyable, ComputationOutput: ~Copyable>(
        borrowing borrowed: borrowing At<L, Borrowed>,
        _ body: (L.Reader, borrowing Borrowed) -> Freer<L.Local, ComputationOutput>
    ) -> Freer<Effs, At<L, ComputationOutput>> {
        locallyRun(borrowed.borrowMap { body(L.Reader(_unchecked: ()), $0) })
    }

    /// Runs the same local code at every location in `S`, taking each one's facet: for noncopyable facets, like each
    /// peer's session, that a later step uses up. Like `locally(consuming:)`, the body runs when the choreography reaches
    /// this step, where each facet is held, and builds the program that runs as the step.
    ///
    ///     let keys = bind(Choreography.parallel(consuming: consume sessions) { facet, session in
    ///         .pure(session.finish(with: facet(peerMessages)))
    ///     })
    static func parallel<Effs: Has, S: LocationSet, Owned: ~Copyable, FacetOutput: ~Copyable>(
        consuming owned: consuming Faceted<S, Owned>,
        _ body: (Facet<S>, consuming Owned) -> Freer<S.Shared, FacetOutput>
    ) -> Freer<Effs, Faceted<S, FacetOutput>> {
        parallelRun(owned.map { location, facet in body(Facet(location: location), facet) })
    }

    /// Runs the same local code at every location in `S`, reading each one's facet and leaving it in place.
    /// The body runs when the choreography reaches this step, so what it reads is read then: copy it into its program.
    ///
    ///     let publicKeys = bind(Choreography.parallel(borrowing: sessions) { _, session in .pure(session.Y) })
    static func parallel<Effs: Has, S: LocationSet, Borrowed: ~Copyable, FacetOutput: ~Copyable>(
        borrowing borrowed: borrowing Faceted<S, Borrowed>,
        _ body: (Facet<S>, borrowing Borrowed) -> Freer<S.Shared, FacetOutput>
    ) -> Freer<Effs, Faceted<S, FacetOutput>> {
        parallelRun(borrowed.borrowMap { location, facet in body(Facet(location: location), facet) })
    }

    /// A value held by the whole census, as a plain value: every participant gets the same one,
    /// so they all take the same path through the code after it
    static func naked<S: LocationSet, V>(_ v: At<S, V>) -> Freer<Within<S>, V> {
        naked(v, in: Census())
    }

    /// A sub-choreography among `Sub` only: everyone else skips it, and only `Sub` holds its result
    static func conclave<S: LocationSet, Sub: LocationSet, B>(
        _ participants: Sub.Type,
        _ subset: Subset<Sub, S>,
        _ body: @escaping () -> Freer<Within<Sub>, B>
    ) -> Freer<Within<S>, At<Sub, B>> {
        conclave(participants, in: Census(), subset, body)
    }

    /// Replaces each choreography effect of `program` by `translation`'s program for it
    static func translate<S: LocationSet, A: ~Copyable, T: Translation>(_ program: consuming Freer<Within<S>, A>, with translation: T) -> Freer<T.Target, A> {
        program.translate(WithinTranslator<S, T>(translator: Translator(translation)))
    }

    /// The program one participant runs: only a member of the census can be projected
    static func project<S: LocationSet, Me: Location, A: ~Copyable>(
        _ program: consuming Freer<Within<S>, A>,
        as participant: Member<Me, S>
    ) -> Freer<Node<Me.Local>, A> {
        translate(program, with: Projector<Me>())
    }

    /// The stack a projected location runs in: its local effects, and the network to talk to the others.
    /// Local code can't reach the network, since `Local` doesn't contain it: only the choreography communicates.
    ///
    ///     try await program.run(with: .init(local: ServerLocal.Interpreter(…), networking: WebSocketNetwork(…)))
    enum Node<Local: EffectStack>: Networking.Has, Embedding.Has {
        public struct Interpreter {
            public var local: Local.Interpreter
            public var networking: any Networking.Interpreter

            public init(local: Local.Interpreter, networking: any Networking.Interpreter) {
                self.local = local
                self.networking = networking
            }
        }

        public static func inject<X: ~Copyable>(_ effect: consuming any Effect<Networking.Family, X> & ~Copyable) -> any Effect<Node<Local>, X> & ~Copyable {
            NodeNetworked<Local, X>.networked(effect)
        }

        /// The projection's own local steps, like `congruently` bodies: they run directly
        public static func inject<X: ~Copyable>(_ effect: consuming any Effect<Embedding.Family, X> & ~Copyable) -> any Effect<Node<Local>, X> & ~Copyable {
            NodeEmbedded<Local, X>.embedded(effect)
        }
    }
}

/// `Within<S>`'s effects are choreography effects that `inject` rehomed, so a choreography translation translates them.
struct WithinTranslator<S: LocationSet, T: Choreography.Translation>: Slingshot.Translation {
    typealias From = Choreography.Within<S>
    typealias To = T.Target

    let translator: Choreography.Translator<T>

    func translate<X: ~Copyable>(_ effect: consuming any Effect<Choreography.Within<S>, X> & ~Copyable) -> Freer<T.Target, X> {
        // into a local first: opening a consuming existential parameter directly trips a compiler bug
        let local = consume effect
        return rehomed(local, as: X.self)
    }

    // Opens the effect, so its type can be compared: `as?` doesn't work on noncopyable values
    private func rehomed<E: Effect & ~Copyable, X: ~Copyable>(_ effect: consuming E, as output: X.Type) -> Freer<T.Target, X>
    where E.Output: ~Copyable {
        guard E.self == Choreography.Rehomed<S, X>.self else {
            preconditionFailure("\(E.self) is in a Within program without coming from Within.inject")
        }
        return translator.translate(unsafeReinterpret(effect, as: Choreography.Rehomed<S, X>.self).take())
    }
}

/// A location's local effect inside its node: run with the node's local interpreter.
enum NodeLifted<Local: EffectStack, X: ~Copyable>: Effect, ~Copyable {
    typealias Family = Choreography.Node<Local>
    typealias Output = X

    case lifted(any Effect<Local, X> & ~Copyable)

    consuming func accept(_ interpreter: Choreography.Node<Local>.Interpreter) async throws -> X {
        switch consume self {
        case .lifted(let effect):
            return try await runEffect(effect, as: X.self, with: interpreter.local)
        }
    }
}

enum NodeNetworked<Local: EffectStack, X: ~Copyable>: Effect, ~Copyable {
    typealias Family = Choreography.Node<Local>
    typealias Output = X

    case networked(any Effect<Networking.Family, X> & ~Copyable)

    consuming func accept(_ interpreter: Choreography.Node<Local>.Interpreter) async throws -> X {
        switch consume self {
        case .networked(let effect):
            return try await runEffect(effect, as: X.self, with: interpreter.networking)
        }
    }
}

enum NodeEmbedded<Local: EffectStack, X: ~Copyable>: Effect, ~Copyable {
    typealias Family = Choreography.Node<Local>
    typealias Output = X

    case embedded(any Effect<Embedding.Family, X> & ~Copyable)

    consuming func accept(_ interpreter: Choreography.Node<Local>.Interpreter) async throws -> X {
        switch consume self {
        case .embedded(let effect):
            return try await runEffect(effect, as: X.self, with: DirectEmbedding())
        }
    }
}

struct DirectEmbedding: Embedding.Interpreter {
    func run<V: ~Copyable>(_ body: @escaping () async throws -> V) async throws -> V {
        try await body()
    }
}

/// Moves a location's local program into its node: each effect is kept, wrapped to run with the local interpreter.
/// It's a hoist, so it doesn't need to know which families the location's stack contains.
struct LiftIntoNode<Local: EffectStack>: Translation {
    typealias From = Local
    typealias To = Choreography.Node<Local>

    func translate<X: ~Copyable>(_ effect: consuming any Effect<Local, X> & ~Copyable) -> Freer<Choreography.Node<Local>, X> {
        .perform(NodeLifted<Local, X>.lifted(effect))
    }
}
