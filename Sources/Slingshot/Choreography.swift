@EffectFamily
public enum Choreography {
    public protocol Interpreter {
        /// runs a local computation at one location L
        func locally<L: Location, ComputationOutput>(
            _ type: L.Type,
            _ body: @escaping (L.Reader) async throws -> ComputationOutput
        ) async throws -> At<L, ComputationOutput>

        /// sends a value at location Sender to every location in Receivers: they all hold it afterwards
        func send<Sender: Location, Receivers: LocationSet, Value: Codable & Sendable>(
            _ v: At<Sender, Value>,
            to: Receivers.Type
        ) async throws -> At<Receivers, Value>

        /// computes the same value at every location in S, from values they all hold: no communication
        func congruently<S: LocationSet, CongruentOutput>(
            _ locations: S.Type,
            _ body: @escaping (Congruent<S>) -> CongruentOutput
        ) async throws -> At<S, CongruentOutput>

        /// runs the same local code at every location in S, each producing its own facet: no communication
        func parallel<S: LocationSet, FacetOutput>(
            _ locations: S.Type,
            _ body: @escaping (Facet<S>) async throws -> FacetOutput
        ) async throws -> Faceted<S, FacetOutput>

        /// sends every location in S's facet to every location in Receivers, who then hold all of them
        func fanIn<S: LocationSet, Receivers: LocationSet, Value: Codable & Sendable>(
            _ facets: Faceted<S, Value>,
            to: Receivers.Type
        ) async throws -> At<Receivers, Quire<S, Value>>

        /// a value held by the whole census as a plain value: every participant holds it, so they all take the
        /// same path through the code after it. Use `Choreography.naked(_:)`, which supplies the census.
        func naked<S: LocationSet, V>(_ v: At<S, V>, in census: Census<S>) async throws -> V

        /// a sub-choreography among Sub only: everyone else skips it and holds nothing of its result.
        /// Use `Choreography.conclave(_:_:_:)`, which supplies the census.
        func conclave<Outer: LocationSet, Sub: LocationSet, B>(
            _ participants: Sub.Type,
            in census: Census<Outer>,
            _ subset: Subset<Sub, Outer>,
            _ body: @escaping () -> Freer<Within<Sub>, B>
        ) async throws -> At<Sub, B>

        /// branches depending on value V at location L
        func branch<L: Location, Value: Codable & Sendable, BranchOutput>(
            _ v: At<L, Value>,
            _ body: @escaping (Value) -> Freer<Choreography.Family, BranchOutput>
        ) async throws -> BranchOutput
    }
}

@EffectFamily
public enum Networking {
    public protocol Interpreter {
        func send<V: Codable & Sendable>(_ value: V, to location: String) async throws
        func receive<V: Codable & Sendable>(_ type: V.Type, from location: String) async throws -> V
        func broadcast<V: Codable & Sendable>(_ value: V) async throws
    }
}

@EffectFamily
public enum Embedding {
    public protocol Interpreter {
        func run<V>(_ body: @escaping () async throws -> V) async throws -> V
    }
}

public struct Projector<Me: Location, Effs: Networking.Has & Embedding.Has>: Choreography.Translation {
    public typealias Target = Effs

    public init() {}

    public func locally<L, ComputationOutput>(
        _ type: L.Type,
        _ body: @escaping (L.Reader) async throws -> ComputationOutput
    ) -> Freer<Effs, At<L, ComputationOutput>> where L : Location {
        guard Me.self == L.self else {
            return .pure(.absent)
        }

        return Embedding.run {
            .init(value: try await body(L.Reader(_unchecked: ())))
        }
    }

    public func send<Sender, Receivers, Value>(
        _ v: At<Sender, Value>,
        to: Receivers.Type
    ) -> Freer<Effs, At<Receivers, Value>> where Sender : Location, Receivers : LocationSet, Value : Codable & Sendable {
        let received = Receivers.contains(Me.self)

        if Sender.self == Me.self {
            let value = v.take()
            // the sender keeps its own copy instead of sending it to itself
            let others = Receivers.members.filter { ObjectIdentifier($0) != ObjectIdentifier(Me.self) }
            let sent = others.reduce(Freer<Effs, Void>.pure(())) { program, receiver in
                program.flatMap { _ in Networking.send(value, to: receiver.name) }
            }
            let result: At<Receivers, Value> = received ? .init(value: value) : .absent
            return sent.map(constant(result))
        }

        if received {
            return Networking.receive(Value.self, from: Sender.name)
                .map(At.init(value:))
        }

        return .pure(.absent)
    }

    public func congruently<S, CongruentOutput>(
        _ locations: S.Type,
        _ body: @escaping (Congruent<S>) -> CongruentOutput
    ) -> Freer<Effs, At<S, CongruentOutput>> where S : LocationSet {
        guard S.contains(Me.self) else {
            return .pure(.absent)
        }

        // run when the program gets here, not when it's translated: "pure" is only a convention for the body
        return Embedding.run {
            .init(value: body(Congruent()))
        }
    }

    public func parallel<S, FacetOutput>(
        _ locations: S.Type,
        _ body: @escaping (Facet<S>) async throws -> FacetOutput
    ) -> Freer<Effs, Faceted<S, FacetOutput>> where S : LocationSet {
        guard S.contains(Me.self) else {
            return .pure(.absent)
        }

        return Embedding.run {
            .init(value: try await body(Facet(location: Me.self)))
        }
    }

    public func fanIn<S, Receivers, Value>(
        _ facets: Faceted<S, Value>,
        to: Receivers.Type
    ) -> Freer<Effs, At<Receivers, Quire<S, Value>>> where S : LocationSet, Receivers : LocationSet, Value : Codable & Sendable {
        let isMe = { (location: any Location.Type) in ObjectIdentifier(location) == ObjectIdentifier(Me.self) }

        // a member sends its facet to every receiver but itself
        var program: Freer<Effs, Void> = .pure(())
        if S.contains(Me.self) {
            let mine = facets.take()
            for receiver in Receivers.members where !isMe(receiver) {
                program = program.flatMap { _ in Networking.send(mine, to: receiver.name) }
            }
        }

        guard Receivers.contains(Me.self) else {
            return program.map(constant(.absent))
        }

        // a receiver collects every member's facet, its own included without a message
        let gathered = S.members.reduce(program.map { _ in [String: Value]() }) { collected, member in
            collected.flatMap { values in
                if isMe(member) {
                    return .pure(values.merging([member.name: facets.take()]) { $1 })
                }
                return Networking.receive(Value.self, from: member.name)
                    .map { values.merging([member.name: $0]) { $1 } }
            }
        }
        return gathered.map { .init(value: Quire(values: $0)) }
    }

    public func naked<S, V>(_ v: At<S, V>, in census: Choreography.Census<S>) -> Freer<Effs, V> where S : LocationSet {
        // only participants are projected, and every participant holds a value located at the census
        .pure(v.take())
    }

    public func conclave<Outer, Sub, B>(
        _ participants: Sub.Type,
        in census: Choreography.Census<Outer>,
        _ subset: Subset<Sub, Outer>,
        _ body: @escaping () -> Freer<Choreography.Within<Sub>, B>
    ) -> Freer<Effs, At<Sub, B>> where Outer : LocationSet, Sub : LocationSet {
        guard Sub.contains(Me.self) else {
            return .pure(.absent)
        }

        return Choreography.translate(body(), with: self)
            .map(At.init(value:))
    }

    public func branch<L, Value, BranchOutput>(
        _ v: At<L, Value>,
        _ body: @escaping (Value) -> Freer<Choreography.Family, BranchOutput>
    ) -> Freer<Effs, BranchOutput> where L : Location, Value: Codable & Sendable {
        let broadcast: Freer<Effs, Value> = if Me.self == L.self {
            Networking.broadcast(v.take())
                .map(constant(v.take()))
        } else {
            Networking.receive(Value.self, from: L.name)
        }

        return broadcast.flatMap {
            Choreography.translate(body($0), with: self)
        }
    }
}

public extension Choreography {
    /// That a program's participants are exactly `S`. Only Slingshot makes one, so census-dependent operations
    /// can only be reached through `Choreography.naked` and `Choreography.conclave`, where the census is the program's own.
    struct Census<S: LocationSet>: Sendable {
        init() {}
    }

    /// The stack of a choreography whose participants are exactly `S`: its census.
    /// Knowing the census lets a value held by all of it be used as a plain value (`naked`), and lets a sub-choreography
    /// run among fewer participants (`conclave`), which is how MultiChor branches without telling uninvolved locations.
    ///
    ///     let program: Freer<Choreography.Within<Everyone>, Done> = #do { bind in … }
    ///     let atServer = Choreography.project(program, as: Server.member(of: Everyone.self), into: ServerStack.self)
    enum Within<S: LocationSet>: Has {
        public typealias Interpreter = Choreography.Family.Interpreter

        public static func inject<X>(_ effect: any Effect<Choreography.Family, X>) -> any Effect<Within<S>, X> {
            Rehomed<S, X>(effect: effect)
        }
    }

    /// A choreography effect in a `Within<S>` program: the same effect, run by the same interpreter.
    struct Rehomed<S: LocationSet, X>: Effect {
        public typealias Family = Within<S>
        public typealias Output = X

        let effect: any Effect<Choreography.Family, X>

        public func accept(_ interpreter: any Choreography.Interpreter) async throws -> X {
            try await effect.accept(interpreter)
        }
    }

    /// A value held by the whole census, as a plain value: every participant gets the same one,
    /// so they all take the same path through the code after it
    static func naked<S: LocationSet, V>(_ v: At<S, V>) -> Freer<Within<S>, V> {
        naked(v, in: Census())
    }

    /// A sub-choreography among `Sub` only: everyone else skips it, and only `Sub` holds its result
    static func conclave<S: LocationSet, Sub: LocationSet, B>(
        _ participants: Sub.Type,
        _ subset: Subset<Sub, S>,
        _ body: @escaping () -> Freer<Within<Sub>, B>
    ) -> Freer<Within<S>, At<Sub, B>> {
        conclave(participants, in: Census(), subset, body)
    }

    /// Replaces each choreography effect of `program` by `translation`'s program for it
    static func translate<S: LocationSet, A, T: Translation>(_ program: Freer<Within<S>, A>, with translation: T) -> Freer<T.Target, A> {
        program.translate(WithinTranslator<S, T>(translator: Translator(translation)))
    }

    /// The program one participant runs: only a member of the census can be projected
    static func project<S: LocationSet, Me: Location, Effs: Networking.Has & Embedding.Has, A>(
        _ program: Freer<Within<S>, A>,
        as participant: Member<Me, S>,
        into stack: Effs.Type = Effs.self
    ) -> Freer<Effs, A> {
        translate(program, with: Projector<Me, Effs>())
    }
}

/// `Within<S>`'s effects are choreography effects that `inject` rehomed, so a choreography translation translates them.
struct WithinTranslator<S: LocationSet, T: Choreography.Translation>: Slingshot.Translation {
    typealias From = Choreography.Within<S>
    typealias To = T.Target

    let translator: Choreography.Translator<T>

    func translate<X>(_ effect: any Effect<Choreography.Within<S>, X>) -> Freer<T.Target, X> {
        guard let rehomed = effect as? Choreography.Rehomed<S, X> else {
            preconditionFailure("\(type(of: effect)) is in a Within program without coming from Within.inject")
        }
        return translator.translate(rehomed.effect)
    }
}
