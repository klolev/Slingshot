// Choreography steps named after where they run, so the location reads first and isn't passed as a type:
//
//     let secret = bind(Alice.locally { _ in .pure(Secret()) })      // Choreography.locally(Alice.self) { … }
//     let words = bind(Pair.parallel { facet in Words.word() })      // Choreography.parallel(Pair.self) { … }
//
// The steps whose location comes from a value are methods of the value: `secret.reading { … }`, `part.send(to: Bob.self)`,
// `parts.fanIn(to: Pair.self)`, `reply.naked()`.
// Reading a noncopyable facet in place, `Alice.locally(borrowing: facets)`, is generated by `@Location`:
// only code generated for one location can require that the set includes it.

public extension Location {
    /// Runs local code here: `Choreography.locally(Self.self, body)`
    static func locally<Effs: Choreography.Has, Output: ~Copyable>(
        _ body: @escaping (Reader) -> Freer<Local, Output>
    ) -> Freer<Effs, At<Self, Output>> {
        Choreography.locally(Self.self, body)
    }

    /// Runs local code here, taking a value held here: `Choreography.locally(consuming:_:)`
    static func locally<Effs: Choreography.Has, Owned: ~Copyable, Output: ~Copyable>(
        consuming owned: consuming At<Self, Owned>,
        _ body: (Reader, consuming Owned) throws -> Freer<Local, Output>
    ) -> Freer<Effs, At<Self, Output>> {
        Choreography.locally(consuming: owned, body)
    }

    /// Runs local code here, reading a value held here in place: `Choreography.locally(borrowing:_:)`
    static func locally<Effs: Choreography.Has, Borrowed: ~Copyable, Output: ~Copyable>(
        borrowing borrowed: borrowing At<Self, Borrowed>,
        _ body: (Reader, borrowing Borrowed) throws -> Freer<Local, Output>
    ) -> Freer<Effs, At<Self, Output>> {
        Choreography.locally(borrowing: borrowed, body)
    }

    /// A constant here: `Choreography.constant(value, at: Self.self)`
    static func constant<Effs: Choreography.Has, V>(_ value: V) -> Freer<Effs, At<Self, V>> {
        Choreography.constant(value, at: Self.self)
    }
}

public extension LocationSet {
    /// Runs the same local code at every member: `Choreography.parallel(Self.self, body)`
    static func parallel<Effs: Choreography.Has, Output: ~Copyable>(
        _ body: @escaping (Facet<Self>) -> Freer<Shared, Output>
    ) -> Freer<Effs, Faceted<Self, Output>> {
        Choreography.parallel(Self.self, body)
    }

    /// Runs the same local code at every member, taking its facet: `Choreography.parallel(consuming:_:)`
    static func parallel<Effs: Choreography.Has, Owned: ~Copyable, Output: ~Copyable>(
        consuming owned: consuming Faceted<Self, Owned>,
        _ body: (Facet<Self>, consuming Owned) throws -> Freer<Shared, Output>
    ) -> Freer<Effs, Faceted<Self, Output>> {
        Choreography.parallel(consuming: owned, body)
    }

    /// Runs the same local code at every member, reading its facet in place: `Choreography.parallel(borrowing:_:)`
    static func parallel<Effs: Choreography.Has, Borrowed: ~Copyable, Output: ~Copyable>(
        borrowing borrowed: borrowing Faceted<Self, Borrowed>,
        _ body: (Facet<Self>, borrowing Borrowed) throws -> Freer<Shared, Output>
    ) -> Freer<Effs, Faceted<Self, Output>> {
        Choreography.parallel(borrowing: borrowed, body)
    }

    /// Computes the same value at every member, from values they all hold: `Choreography.congruently(Self.self, body)`
    static func congruently<Effs: Choreography.Has, Output>(
        _ body: @escaping (Congruent<Self>) -> Output
    ) -> Freer<Effs, At<Self, Output>> {
        Choreography.congruently(Self.self, body)
    }
}

// Local steps driven by the value they work on: its type already says where it's held.
//
//     let publicPart = bind(secret.reading { s in .pure(s.publicPart) })
//     let finished = bind((consume secret).using { s, reader in .pure(s.finish(with: reader(answer))) })
//
// `reading` leaves the value in place and `using` takes it. Each comes with or without the reader (or, for facets,
// the facet), told apart by the closure's parameters. Like `locally(consuming:)`, the body runs when the
// choreography reaches the step, only where the value is held: keep it to computing, and put effects in the program it returns.

public extension At where S: Location, Value: ~Copyable {
    /// Runs local code where the value is held, reading it in place: `Choreography.locally(borrowing:_:)`
    borrowing func reading<Effs: Choreography.Has, Output: ~Copyable>(
        _ body: (borrowing Value) throws -> Freer<S.Local, Output>
    ) -> Freer<Effs, At<S, Output>> {
        Choreography.locally(borrowing: self) { _, value in try body(value) }
    }

    /// Runs local code where the value is held, reading it in place, with the location's reader for other values
    borrowing func reading<Effs: Choreography.Has, Output: ~Copyable>(
        _ body: (borrowing Value, S.Reader) throws -> Freer<S.Local, Output>
    ) -> Freer<Effs, At<S, Output>> {
        Choreography.locally(borrowing: self) { reader, value in try body(value, reader) }
    }

    /// Runs local code where the value is held, taking it: `Choreography.locally(consuming:_:)`
    consuming func using<Effs: Choreography.Has, Output: ~Copyable>(
        _ body: (consuming Value) throws -> Freer<S.Local, Output>
    ) -> Freer<Effs, At<S, Output>> {
        Choreography.locally(consuming: self) { _, value in try body(value) }
    }

    /// Runs local code where the value is held, taking it, with the location's reader for other values
    consuming func using<Effs: Choreography.Has, Output: ~Copyable>(
        _ body: (consuming Value, S.Reader) throws -> Freer<S.Local, Output>
    ) -> Freer<Effs, At<S, Output>> {
        Choreography.locally(consuming: self) { reader, value in try body(value, reader) }
    }
}

public extension Faceted where Value: ~Copyable {
    /// Runs the same local code at every member, reading its facet in place: `Choreography.parallel(borrowing:_:)`
    borrowing func reading<Effs: Choreography.Has, Output: ~Copyable>(
        _ body: (borrowing Value) throws -> Freer<S.Shared, Output>
    ) -> Freer<Effs, Faceted<S, Output>> {
        Choreography.parallel(borrowing: self) { _, value in try body(value) }
    }

    /// Runs the same local code at every member, reading its facet in place, with the member's `Facet` for other values
    borrowing func reading<Effs: Choreography.Has, Output: ~Copyable>(
        _ body: (borrowing Value, Facet<S>) throws -> Freer<S.Shared, Output>
    ) -> Freer<Effs, Faceted<S, Output>> {
        Choreography.parallel(borrowing: self) { facet, value in try body(value, facet) }
    }

    /// Runs the same local code at every member, taking its facet: `Choreography.parallel(consuming:_:)`
    consuming func using<Effs: Choreography.Has, Output: ~Copyable>(
        _ body: (consuming Value) throws -> Freer<S.Shared, Output>
    ) -> Freer<Effs, Faceted<S, Output>> {
        Choreography.parallel(consuming: self) { _, value in try body(value) }
    }

    /// Runs the same local code at every member, taking its facet, with the member's `Facet` for other values
    consuming func using<Effs: Choreography.Has, Output: ~Copyable>(
        _ body: (consuming Value, Facet<S>) throws -> Freer<S.Shared, Output>
    ) -> Freer<Effs, Faceted<S, Output>> {
        Choreography.parallel(consuming: self) { facet, value in try body(value, facet) }
    }
}

public extension At where S: Location, Value: Codable & Sendable {
    /// Sends the value to every location in `receivers`: `Choreography.send(self, to: receivers)`
    ///
    ///     let atBob = bind(publicPart.send(to: Bob.self))
    func send<Effs: Choreography.Has, Receivers: LocationSet>(to receivers: Receivers.Type) -> Freer<Effs, At<Receivers, Value>> {
        Choreography.send(self, to: receivers)
    }
}

public extension At where Value: Copyable {
    /// The value as a plain one, when the whole census holds it: `Choreography.naked(self)`
    ///
    ///     if let session = await joinResponse.naked() { … }
    func naked() -> Freer<Choreography.Within<S>, Value> {
        Choreography.naked(self)
    }
}

public extension Faceted where Value: Codable & Sendable {
    /// Sends every member's facet to every location in `receivers`: `Choreography.fanIn(self, to: receivers)`
    ///
    ///     let allParts = bind(publicParts.fanIn(to: Pair.self))
    func fanIn<Effs: Choreography.Has, Receivers: LocationSet>(to receivers: Receivers.Type) -> Freer<Effs, At<Receivers, Quire<S, Value>>> {
        Choreography.fanIn(self, to: receivers)
    }
}
